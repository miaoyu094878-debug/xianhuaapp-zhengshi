-- 用户内容云同步（补齐）
-- 背景：目标 / 活跃天数 / 肯定语收藏 已有表（goals / active_days / affirm_favs / affirm_custom），
-- 但「愿景板卡片」和「收藏内容」没有对应表，导致这两类内容只存在本地、无法随账号走。
-- 本迁移只补这两张缺失的表；RLS 与既有表保持一致（owner all：auth.uid() = user_id）。
-- 迁移后请顺手更新 supabase/SCHEMA.md。

-- 愿景板卡片：emoji + 文字 + 可选配图（配图为压缩后的 data URL，用户自行上传，数量有限）
create table if not exists public.vision_cards (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null,
  emoji      text not null default '✦',
  text       text not null default '',
  photo      text not null default '',
  created_at timestamptz not null default now()
);

alter table public.vision_cards enable row level security;

drop policy if exists "owner all vision_cards" on public.vision_cards;
create policy "owner all vision_cards" on public.vision_cards
  for all to public
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- 收藏内容（Saved Inspiration）：文字 / 标题 / 链接 / 时间戳 / 来源
-- 注意：列名用 source 而非 from（from 是 SQL 保留字）
create table if not exists public.saved_content (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null,
  text       text not null default '',
  title      text not null default '',
  link       text not null default '',
  ts         bigint not null default 0,
  source     text not null default 'paste',
  created_at timestamptz not null default now()
);

alter table public.saved_content enable row level security;

drop policy if exists "owner all saved_content" on public.saved_content;
create policy "owner all saved_content" on public.saved_content
  for all to public
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- 授权：Supabase 默认会把新表的权限给 authenticated，这里显式补一次，避免漏授权。
grant all on public.vision_cards  to authenticated;
grant all on public.saved_content  to authenticated;
grant usage, select on all sequences in schema public to authenticated;
